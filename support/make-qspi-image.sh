#!/bin/sh
#
# Build a complete QSPI0 boot flash image from an SBL *.tl-image.
#
# The *.tl-image produced by the SBL build is a gzipped tar with a
# package.toml that describes the actions to perform on the SPI NOR
# flash (see the ELVEES tl-sbimg tool).  mcom03-flash replays those
# actions over the BootROM UART.  When the BootROM UART monitor is not
# available the very same content can be written to the flash chip
# directly with an external programmer (flashrom, CH341A, ...); this
# script turns the tl-image into a flat image of the whole flash chip.
#
# Layout (from package.toml, profile "sbimg"):
#
#   0x000000  bootrom SBIMG parsed by the BootROM
#   0x200000  SBL SBIMG parsed by the SBL
#   0xFD0000  SBL environment (erased, 64 KiB)
#   0xFE0000  U-Boot environment, two erased 64 KiB sectors
#
# Everything else is filled with 0xFF (the erased state of a NOR flash).
#
# Usage:
#   make-qspi-image.sh [-s SIZE] [-o OUTPUT] TL_IMAGE
#
#   -s SIZE         flash size in bytes (default: 0x1000000, 16 MiB)
#   -o FILE         output file (default: <tl-image>.qspi.bin)
#
# Copyright (C) 2026 INMYS

set -eu

PROG=$(basename "$0")

die() {
	echo "$PROG: $*" >&2
	exit 1
}

flash_size=$((16 * 1024 * 1024))
output=
tl_image=

while [ $# -gt 0 ]; do
	case "$1" in
	-s|--size)      flash_size=$(($2)); shift 2 ;;
	-o|--output)    output=$2; shift 2 ;;
	-h|--help)      sed -n '2,27p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
	-*)             die "unknown option: $1" ;;
	*)              tl_image=$1; shift ;;
	esac
done

[ -n "$tl_image" ] || die "no tl-image given (try --help)"
[ -f "$tl_image" ] || die "no such file: $tl_image"
[ -n "$output" ] || output="$tl_image.qspi.bin"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT INT TERM

tar -xzf "$tl_image" -C "$tmp" || die "cannot unpack $tl_image"
[ -f "$tmp/package.toml" ] || die "$tl_image has no package.toml"

# ------------------------------------------------------------------
# Parse [profile.sbimg] from package.toml.
#
# The file is generated by our own SBL build, so a small section parser
# is enough: collect "<action>.<field> = <value>" pairs of the sbimg
# profile and print one "command|offset|size|negative|name" line per
# action, in file order.
# ------------------------------------------------------------------
layout=$(awk '
	/^[ \t]*\[/ {
		section = $0
		gsub(/[ \t]/, "", section)
		next
	}
	section != "[profile.sbimg]" { next }
	/^[ \t]*#/ { next }
	/=/ {
		line = $0
		sub(/#.*/, "", line)
		key = line; sub(/=.*/, "", key); gsub(/[ \t]/, "", key)
		val = line; sub(/^[^=]*=/, "", val)
		gsub(/^[ \t]+|[ \t]+$/, "", val); gsub(/"/, "", val)
		split(key, k, ".")
		if (k[2] == "") next
		v[k[1], k[2]] = val
		if (!(k[1] in seen)) { seen[k[1]] = 1; order[++n] = k[1] }
	}
	END {
		for (i = 1; i <= n; i++) {
			a = order[i]
			printf "%s|%s|%s|%s|%s\n",
				v[a, "command"], v[a, "offset"], v[a, "size"],
				v[a, "negative_offset"], v[a, "name"]
		}
	}
' "$tmp/package.toml")

[ -n "$layout" ] || die "no [profile.sbimg] actions in package.toml"

# ------------------------------------------------------------------
# Start from an erased (0xFF) chip.
# ------------------------------------------------------------------
head -c "$flash_size" /dev/zero | tr '\000' '\377' > "$output" || \
	die "cannot create $output"

layout_txt="${output%.bin}.layout.txt"
{
	echo "# QSPI0 boot flash image"
	echo "# source: $(basename "$tl_image")"
	echo "# size:   $flash_size bytes (0x$(printf '%x' "$flash_size"))"
	echo "#"
	printf '%-10s %-10s %-10s %s\n' "offset" "size" "action" "content"
} > "$layout_txt"


echo "$layout" | while IFS='|' read -r command offset size negative name; do
	[ -n "$command" ] || continue
	[ -n "$offset" ] || offset=0
	off=$((offset))

	# A negative offset is counted from the end of the flash.
	if [ "$negative" = "true" ]; then
		off=$((flash_size - off))
	fi

	case "$command" in
	flash)
		[ -n "$name" ] || die "flash action without a file name"
		[ -f "$tmp/$name" ] || die "$tl_image does not contain $name"
		bytes=$(stat -c %s "$tmp/$name")
		[ $((off + bytes)) -le "$flash_size" ] || \
			die "$name does not fit into the $flash_size byte flash"
		dd if="$tmp/$name" of="$output" bs=1 seek="$off" conv=notrunc 2>/dev/null
		printf '%-10s %-10s %-10s %s\n' "0x$(printf '%06x' "$off")" \
			"$bytes" "flash" "$name" >> "$layout_txt"
		;;
	erase)
		[ -n "$size" ] || size=0x10000
		size=$((size))
		printf '%-10s %-10s %-10s %s\n' "0x$(printf '%06x' "$off")" \
			"$size" "erase" "0xFF (erased)" >> "$layout_txt"
		;;
	*)
		die "unknown action '$command' in package.toml"
		;;
	esac
done

sha256sum "$output" > "$output.sha256"

echo "$PROG: $(basename "$output")"
sed 's/^/  /' "$layout_txt"
echo "  sha256: $(cut -d' ' -f1 "$output.sha256")"
